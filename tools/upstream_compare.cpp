// Independent benchmark driver, paired with examples/upstream_compare.rs.
// The upstream library is an external checkout with its original license.
#include <fast_io_freestanding.h>
#include <fast_io_dsal/string.h>
#include <array>
#include <bit>
#include <chrono>
#include <cstdint>
#include <cstdio>
#include <fstream>
#include <stdexcept>
#include <string>
#include <string_view>
#include <vector>

constexpr std::size_t record_count = 1024;
constexpr std::uint64_t multiplier = 6364136223846793005ULL;

struct record {
    std::uint64_t id;
    std::int64_t delta;
    std::string name;
    bool active;
};

auto make_records(std::size_t payload) {
    std::vector<record> records;
    records.reserve(record_count);
    constexpr std::array<std::size_t, 3> lengths{1, 12, 96};
    for (std::size_t index{}; index != record_count; ++index) {
        auto id = static_cast<std::uint64_t>(index) * multiplier;
        if (index == 0) id = 0;
        if (index == 1) id = UINT64_MAX;
        if (index == 2) id = std::uint64_t{1} << 63;
        records.push_back({id, std::bit_cast<std::int64_t>(id),
            std::string(payload ? payload : lengths[index % 3], static_cast<char>('a' + index % 26)),
            index % 3 != 0});
    }
    return records;
}

template <typename Output>
void encode(Output&& output, record const& value) {
    fast_io::operations::print_freestanding<true>(output,
        "id=", value.id, " delta=", value.delta, " name=",
        fast_io::mnp::strvw(value.name), " active=", fast_io::mnp::boolalpha(value.active));
}

// Clang compiler barriers, not hardware fences. Match Rust black_box's role:
// make the input opaque and force each generated byte range to remain observable.
inline record const& opaque(record const& value) {
    auto pointer = &value;
    asm volatile("" : "+r"(pointer) : : "memory");
    return *pointer;
}
inline void escape(char const* data, std::size_t size) {
    asm volatile("" : : "r"(data), "r"(size) : "memory");
}

void verify(std::vector<record> const& records, char const* path, std::size_t capacity) {
    std::ofstream file(path, std::ios::binary | std::ios::trunc);
    file.exceptions(std::ios::failbit | std::ios::badbit);
    std::vector<char> storage(capacity);
    fast_io::obuffer_view slice{storage};
    fast_io::string grow;
    grow.reserve(capacity);
    for (auto const& value : records) {
        slice.clear();
        grow.clear();
        encode(slice, value);
        encode(fast_io::ostring_ref_fast_io{&grow}, value);
        auto expected = "id=" + std::to_string(value.id) + " delta=" + std::to_string(value.delta)
            + " name=" + value.name + " active=" + (value.active ? "true\n" : "false\n");
        if (std::string_view(slice.data(), slice.size()) != expected ||
            std::string_view(grow.data(), grow.size()) != expected)
            throw std::runtime_error("formatted bytes differ");
        file.write(grow.data(), static_cast<std::streamsize>(grow.size()));
    }
}

auto memory(std::string_view mode, std::vector<record> const& records,
            std::size_t count, std::size_t capacity) {
    std::vector<char> storage(capacity);
    fast_io::obuffer_view slice{storage};
    fast_io::string grow;
    grow.reserve(capacity);
    std::uint64_t total{};
    auto start = std::chrono::steady_clock::now();
    if (mode == "slice") {
        for (std::size_t index{}; index != count; ++index) {
            slice.clear();
            encode(slice, opaque(records[index % record_count]));
            escape(slice.data(), slice.size());
            total += slice.size();
        }
    } else {
        for (std::size_t index{}; index != count; ++index) {
            grow.clear();
            encode(fast_io::ostring_ref_fast_io{&grow}, opaque(records[index % record_count]));
            escape(grow.data(), grow.size());
            total += grow.size();
        }
    }
    auto elapsed = std::chrono::duration_cast<std::chrono::nanoseconds>(
        std::chrono::steady_clock::now() - start).count();
    return std::pair{elapsed, total};
}

auto parse(std::string const& data) {
    escape(data.data(), data.size());
    fast_io::ibuffer_view input{data};
    std::uint64_t value{}, sum{};
    std::size_t count{};
    // The freestanding entry beneath io::scan_some avoids unrelated hosted APIs.
    while (fast_io::operations::decay::scan_some_freestanding_decay(
        fast_io::operations::input_stream_ref(input),
        fast_io::io_scan_forward<char>(fast_io::io_scan_alias(value)))) {
        ++count;
        sum += value;
    }
    asm volatile("" : "+r"(count), "+r"(sum) : : "memory");
    return std::pair{count, sum};
}

int main(int argc, char** argv) {
    if (argc < 4) throw std::runtime_error("MODE COUNT PAYLOAD [OUTPUT]");
    std::string_view mode{argv[1]};
    auto count = std::stoull(argv[2]);
    auto payload = std::stoull(argv[3]);
    if (!count || payload > SIZE_MAX - 128) throw std::runtime_error("invalid count/payload");
    auto records = make_records(payload);
    auto capacity = std::max<std::size_t>(payload, 96) + 128;
    if (mode == "verify") {
        if (argc < 5) throw std::runtime_error("missing verification output");
        verify(records, argv[4], capacity);
        return 0;
    }
    std::int64_t elapsed{};
    std::uint64_t bytes{}, checksum{};
    if (mode.starts_with("scan")) {
        std::uint64_t mask;
        if (mode == "scan") mask = UINT64_MAX;
        else if (mode == "scan-u8") mask = UINT8_MAX;
        else if (mode == "scan-u32") mask = UINT32_MAX;
        else throw std::runtime_error("unknown scan mode");
        std::string data;
        std::uint64_t expected{};
        for (std::size_t index{}; index != count; ++index) {
            auto value = records[index % record_count].id & mask;
            data += std::to_string(value) + '\n';
            expected += value;
        }
        auto wanted = std::pair{static_cast<std::size_t>(count), expected};
        if (parse(data) != wanted) throw std::runtime_error("warmup scan differs");
        auto start = std::chrono::steady_clock::now();
        auto actual = parse(data);
        elapsed = std::chrono::duration_cast<std::chrono::nanoseconds>(
            std::chrono::steady_clock::now() - start).count();
        if (actual != wanted) throw std::runtime_error("scan differs");
        bytes = data.size();
        checksum = actual.second;
    } else {
        if (mode != "slice" && mode != "grow") throw std::runtime_error("unknown mode");
        memory(mode, records, 10000, capacity);
        auto result = memory(mode, records, count, capacity);
        elapsed = result.first;
        bytes = result.second;
    }
    std::printf("{\"elapsed_ns\":%lld,\"units\":%llu,\"bytes\":%llu,\"checksum\":%llu}\n",
        static_cast<long long>(elapsed), static_cast<unsigned long long>(count),
        static_cast<unsigned long long>(bytes), static_cast<unsigned long long>(checksum));
}
